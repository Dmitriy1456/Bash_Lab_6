#!/bin/bash

# Проверка количества переданных аргументов (должно быть 3)
if [ "$#" -ne 3 ]; then
    echo "Ошибка: Неверное количество аргументов."
    echo "Использование: $0 <путь_к_директории> <старая_строка> <новая_строка>"
    exit 1
fi

# Присвоение аргументов переменным с осмысленными именами
TARGET_DIR="$1"
OLD_STRING="$2"
NEW_STRING="$3"

# Проверка, существует ли указанная директория
if [ ! -d "$TARGET_DIR" ]; then
    echo "Ошибка: Указанный путь '$TARGET_DIR' не существует или не является директорией."
    exit 1
fi

# Основа

echo "Директория: $TARGET_DIR"
echo "Выполняется замена: '$OLD_STRING' -> '$NEW_STRING' во всех .txt файлах..."

# Поиск и замена текста:
# find ищет все обычные файлы (-type f) с расширением .txt
# -exec передает их команде sed.
find "$TARGET_DIR" -type f -name "*.txt" -exec sed -i "s|$OLD_STRING|$NEW_STRING|g" {} +

# Сохраняем статус завершения
EXEC_STATUS=$?

# Чекаем результыты выполнения 

if [ $EXEC_STATUS -eq 0 ]; then
    echo "Успех: Текст успешно заменен!"
    exit 0
else
    echo "Критическая ошибка: Команда замены завершилась со сбоем (код ошибки $EXEC_STATUS)."
    exit $EXEC_STATUS
fi

